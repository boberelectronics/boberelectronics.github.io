/** Exercise the actual hero carousel and five-review renderer with deterministic timers. */
import assert from 'node:assert/strict';
import { makeHarness } from './test-dom.mjs';

const harness = makeHarness({ hero: true, reviews: true });
const { nodes, window, document, timers, advance } = harness;
const items = window.BOBER_DATA.heroCloseups;
const total = items.length;
const slides = nodes['hero-slides'].children;
const dots = nodes['hero-dots'].children;
const previous = nodes['hero-prev'];
const next = nodes['hero-next'];
const pause = nodes['hero-pause'];
function active(h = harness) {
  const index = h.nodes['hero-slides'].children.findIndex(slide => slide.classList.contains('is-active'));
  assert.equal(h.nodes['hero-slides'].children.filter(slide => slide.classList.contains('is-active')).length, 1);
  h.nodes['hero-slides'].children.forEach((slide, position) => assert.equal(slide.getAttribute('aria-hidden'), String(position !== index)));
  h.nodes['hero-dots'].children.forEach((dot, position) => assert.equal(dot.getAttribute('aria-pressed'), String(position === index)));
  assert.equal(h.nodes['hero-position'].textContent, `${String(index + 1).padStart(2, '0')} / ${String(total).padStart(2, '0')}`);
  return index;
}
assert.equal(items.length, 8);
assert.equal(slides.length, 8);
assert.equal(dots.length, 8);
assert.equal(active(), 0);
slides.forEach((slide, index) => {
  const image = slide.querySelector('img');
  assert.equal(slide.getAttribute('role'), 'group');
  assert.equal(slide.getAttribute('aria-roledescription'), 'slide');
  assert.equal(image.alt, items[index].alt);
  assert.equal(image.dataset.src, window.BOBER_UTILS.encodeImagePath(items[index].fullImage));
  assert.equal(image.style.objectFit, 'contain');
  assert.equal(slide.querySelector('figcaption'), null, 'Hero photographs must not render visible caption text');
  assert.equal(dots[index].getAttribute('aria-controls'), slide.id);
  if (index < 2) assert.equal(image.src, image.dataset.src);
  else assert.equal(image.src, undefined, 'Only the first and next optimized photographs should load initially');
});
assert.equal(slides[0].querySelector('img').loading, 'eager');
assert.equal(slides[0].querySelector('img').fetchPriority, 'high');
assert.equal(timers.size, 1);
assert.equal([...timers.values()][0].delay, 6000);
advance(5999);
assert.equal(active(), 0);
advance(1);
assert.equal(active(), 1);
previous.focus();
previous.emit('click');
assert.equal(active(), 0);
previous.emit('click');
assert.equal(active(), total - 1, 'Previous should wrap from the first close-up to the last');
assert.equal(document.activeElement, previous);
next.focus();
next.emit('click');
assert.equal(active(), 0, 'Next should wrap from the last close-up to the first');
assert.equal(document.activeElement, next);
dots[4].focus();
dots[4].emit('click');
assert.equal(active(), 4);
assert.equal(document.activeElement, dots[4]);
assert.equal(dots[4].isConnected, true, 'Changing slides must retain the focused dot node');
assert.equal(nodes['hero-position'].getAttribute('aria-live'), 'polite');
assert.equal(nodes['hero-dots'].children[4], dots[4]);
assert.equal(slides[4].querySelector('img').src, window.BOBER_UTILS.encodeImagePath(items[4].fullImage));
pause.emit('click');
assert.equal(pause.getAttribute('aria-label'), 'Play slideshow');
assert.equal(pause.getAttribute('aria-pressed'), 'true');
assert.equal(timers.size, 0);
advance(18000);
assert.equal(active(), 4);
next.emit('click');
assert.equal(active(), 5, 'Manual navigation must remain available while paused');
assert.equal(timers.size, 0, 'Manual navigation must not cancel the user pause');
previous.emit('click');
assert.equal(active(), 4);
assert.equal(timers.size, 0);
harness.setHidden(true);
harness.setHidden(false);
harness.setIntersecting(false);
harness.setIntersecting(true);
harness.setReducedMotion(true);
harness.setReducedMotion(false);
assert.equal(timers.size, 0, 'Visibility and preference changes must retain an explicit user pause');
pause.emit('click');
assert.equal(pause.getAttribute('aria-label'), 'Pause slideshow');
assert.equal(timers.size, 1);
harness.setHidden(true);
assert.equal(timers.size, 0);
advance(6000);
assert.equal(active(), 4);
harness.setHidden(false);
assert.equal(timers.size, 1);
harness.setIntersecting(false);
assert.equal(timers.size, 0);
harness.setIntersecting(true);
assert.equal(timers.size, 1);
advance(6000);
assert.equal(active(), 5);
window.emit('pagehide');
assert.equal(timers.size, 0, 'Leaving the page should clear the carousel timer');

const reduced = makeHarness({ hero: true, reducedMotion: true });
assert.equal(reduced.timers.size, 0, 'Reduced-motion mode must not schedule automatic rotation');
assert.equal(reduced.nodes['hero-pause'].disabled, true);
assert.match(reduced.nodes['hero-pause'].getAttribute('aria-label'), /reduced motion/i);
reduced.nodes['hero-next'].emit('click');
assert.equal(active(reduced), 1, 'Manual carousel controls must still work with reduced motion');
assert.equal(reduced.timers.size, 0);
reduced.setReducedMotion(false);
assert.equal(reduced.timers.size, 1);
reduced.setReducedMotion(true);
assert.equal(reduced.timers.size, 0);

const reviews = nodes['featured-reviews-list'].children;
assert.equal(reviews.length, 5, 'Exactly the five original highlighted reviews should render');
assert.equal(reviews[0].classList.contains('review-featured'), true);
reviews.forEach((card, index) => {
  const review = window.BOBER_DATA.featuredReviews[index];
  assert.notEqual(card.hidden, true, 'Highlighted reviews should be visible together');
  assert.equal(card.querySelector('blockquote').textContent, review.text);
  assert.equal(card.querySelector('.review-author').textContent, review.user);
  assert.equal(card.querySelector('time').textContent, review.date);
});
assert.equal(window.BOBER_DATA.additionalReviews.length, 38, 'Removing the public section must preserve the original feedback data');
console.log('PASS: Eight authentic hero close-ups retain correct frames and alternative text without visible captions, lazy image loading, wraparound controls, stable dot/control focus, and exact 6-second rotation.');
console.log('PASS: User pause, reduced motion, hidden page, offscreen suspension and page-exit cleanup pass actual-handler checks; all five original highlighted reviews render together verbatim.');
